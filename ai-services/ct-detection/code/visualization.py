def build_viewer_annotation(
    nodule: Dict[str, Any],
) -> Dict[str, Any]:

    physical = (
        nodule[
            "physical_world"
        ]
    )

    original = (
        nodule[
            "original_voxel"
        ]
    )

    return {
        "annotation_id":
            nodule[
                "nodule_id"
            ],

        "type":
            "3D_BOUNDING_BOX",

        "score":
            float(
                nodule[
                    "score"
                ]
            ),

        "world_coordinate_system":
            "XYZ_mm",

        "center_world_xyz_mm":
            physical[
                "center_xyz_mm"
            ],

        "bbox_world": {
            "min_xyz_mm":
                physical[
                    "bbox_min_xyz_mm"
                ],

            "max_xyz_mm":
                physical[
                    "bbox_max_xyz_mm"
                ],

            "corners_xyz_mm":
                physical[
                    "bbox_corners_xyz_mm"
                ],
        },

        "original_voxel": {
            "center_zyx":
                original[
                    "center_zyx"
                ],

            "bbox_min_zyx":
                original[
                    "bbox_min_zyx"
                ],

            "bbox_max_zyx":
                original[
                    "bbox_max_zyx"
                ],
        },

        "slice_range_z":
            nodule[
                "viewer_helper"
            ][
                "original_slice_range_z"
            ],

        "display": {
            "label":
                (
                    f"{nodule['nodule_id']} "
                    f"{nodule['score']:.3f}"
                ),

            "show_score":
                True,

            "show_center":
                True,

            "show_bbox":
                True,
        },
    }


# =============================================================================
# COMPLETE VISUALIZATION
# =============================================================================

def generate_visualizations(
    input_ct: Path | str,
    detection_json: Path | str,
    output_dir: Path | str,
    series_uid: Optional[str] = None,
    max_nodules: int = MAX_VISUALIZED_NODULES,
):

    output_dir = Path(
        output_dir
    )

    axial_dir = (
        output_dir
        / "axial"
    )

    coronal_dir = (
        output_dir
        / "coronal"
    )

    sagittal_dir = (
        output_dir
        / "sagittal"
    )

    preview_3d_dir = (
        output_dir
        / "preview_3d"
    )

    for directory in [
        axial_dir,
        coronal_dir,
        sagittal_dir,
        preview_3d_dir,
    ]:

        directory.mkdir(
            parents=True,
            exist_ok=True,
        )

    # -------------------------------------------------------------------------
    # Load
    # -------------------------------------------------------------------------

    _, volume = (
        load_ct(
            input_path=input_ct,
            series_uid=series_uid,
        )
    )

    detection_data = (
        load_json(
            detection_json
        )
    )

    nodules = (
        detection_data.get(
            "nodules",
            []
        )
    )

    # score descending
    nodules = sorted(
        nodules,
        key=lambda item: float(
            item[
                "score"
            ]
        ),
        reverse=True,
    )

    # 여기서는 PNG 폭발 방지를 위해 상위 N개만 생성.
    #
    # Viewer annotation JSON은 전체 candidate를 저장한다.
    selected = nodules[
        :
        max_nodules
    ]

    print(
        "CT shape ZYX:",
        list(
            volume.shape
        ),
    )

    print(
        "Total detections:",
        len(
            nodules
        ),
    )

    print(
        "PNG visualized:",
        len(
            selected
        ),
    )

    # -------------------------------------------------------------------------
    # PNG
    # -------------------------------------------------------------------------

    manifest = []

    for index, nodule in enumerate(
        selected,
        start=1,
    ):

        nodule_id = (
            nodule[
                "nodule_id"
            ]
        )

        base_name = (
            f"{index:03d}_"
            f"{nodule_id}"
        )

        axial_path = (
            axial_dir
            / f"{base_name}.png"
        )

        coronal_path = (
            coronal_dir
            / f"{base_name}.png"
        )

        sagittal_path = (
            sagittal_dir
            / f"{base_name}.png"
        )

        preview_path = (
            preview_3d_dir
            / f"{base_name}.png"
        )

        draw_axial(
            volume=volume,
            nodule=nodule,
            output_path=axial_path,
        )

        draw_coronal(
            volume=volume,
            nodule=nodule,
            output_path=coronal_path,
        )

        draw_sagittal(
            volume=volume,
            nodule=nodule,
            output_path=sagittal_path,
        )

        draw_3d_bbox(
            nodule=nodule,
            output_path=preview_path,
        )

        manifest.append(
            {
                "nodule_id":
                    nodule_id,

                "rank":
                    index,

                "score":
                    float(
                        nodule[
                            "score"
                        ]
                    ),

                "axial_png":
                    str(
                        axial_path
                    ),

                "coronal_png":
                    str(
                        coronal_path
                    ),

                "sagittal_png":
                    str(
                        sagittal_path
                    ),

                "preview_3d_png":
                    str(
                        preview_path
                    ),
            }
        )

        print(
            f"[{index}/{len(selected)}] "
            f"{nodule_id} "
            f"score={nodule['score']:.4f}"
        )

    # -------------------------------------------------------------------------
    # Viewer annotations - ALL detections
    # -------------------------------------------------------------------------

    annotations = [
        build_viewer_annotation(
            nodule
        )

        for nodule in nodules
    ]

    viewer_payload = {
        "status":
            "SUCCESS",

        "case_id":
            detection_data.get(
                "case_id"
            ),

        "series_uid":
            detection_data.get(
                "series_uid"
            ),

        "annotation_coordinate_system":
            "patient physical XYZ mm",

        "annotation_count":
            len(
                annotations
            ),

        "annotations":
            annotations,
    }

    viewer_path = (
        output_dir
        / "viewer_annotations.json"
    )

    with open(
        viewer_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            viewer_payload,
            file,
            indent=2,
            ensure_ascii=False,
        )

    # -------------------------------------------------------------------------
    # Visualization manifest
    # -------------------------------------------------------------------------

    manifest_path = (
        output_dir
        / "visualization_manifest.json"
    )

    with open(
        manifest_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            manifest,
            file,
            indent=2,
            ensure_ascii=False,
        )

    return {
        "viewer_annotations":
            viewer_path,

        "visualization_manifest":
            manifest_path,

        "axial_dir":
            axial_dir,

        "coronal_dir":
            coronal_dir,

        "sagittal_dir":
            sagittal_dir,

        "preview_3d_dir":
            preview_3d_dir,
    }


