# =============================================================================
# 3D BBOX PREVIEW
# =============================================================================

def bbox_edges(
    corners: np.ndarray,
) -> List[
    Tuple[
        np.ndarray,
        np.ndarray,
    ]
]:

    pairs = [
        (0, 1),
        (0, 2),
        (0, 4),

        (1, 3),
        (1, 5),

        (2, 3),
        (2, 6),

        (3, 7),

        (4, 5),
        (4, 6),

        (5, 7),

        (6, 7),
    ]

    return [
        (
            corners[a],
            corners[b],
        )

        for a, b in pairs
    ]


def draw_3d_bbox(
    nodule: Dict[str, Any],
    output_path: Path,
):

    corners_xyz = np.asarray(
        nodule[
            "physical_world"
        ][
            "bbox_corners_xyz_mm"
        ],
        dtype=np.float64,
    )

    center_xyz = np.asarray(
        nodule[
            "physical_world"
        ][
            "center_xyz_mm"
        ],
        dtype=np.float64,
    )

    edges = (
        bbox_edges(
            corners_xyz
        )
    )

    segments = [
        [
            edge[0],
            edge[1],
        ]

        for edge in edges
    ]

    fig = plt.figure(
        figsize=(
            8,
            8,
        )
    )

    ax = fig.add_subplot(
        111,
        projection="3d",
    )

    collection = (
        Line3DCollection(
            segments,
            linewidths=2,
        )
    )

    ax.add_collection3d(
        collection
    )

    ax.scatter(
        [
            center_xyz[0]
        ],
        [
            center_xyz[1]
        ],
        [
            center_xyz[2]
        ],
        marker="o",
        s=60,
    )

    mins = (
        corners_xyz.min(
            axis=0
        )
    )

    maxs = (
        corners_xyz.max(
            axis=0
        )
    )

    padding = max(
        float(
            np.max(
                maxs - mins
            )
        )
        * 0.25,
        2.0,
    )

    ax.set_xlim(
        mins[0] - padding,
        maxs[0] + padding,
    )

    ax.set_ylim(
        mins[1] - padding,
        maxs[1] + padding,
    )

    ax.set_zlim(
        mins[2] - padding,
        maxs[2] + padding,
    )

    ax.set_xlabel(
        "World X (mm)"
    )

    ax.set_ylabel(
        "World Y (mm)"
    )

    ax.set_zlabel(
        "World Z (mm)"
    )

    ax.set_title(
        (
            f"{nodule['nodule_id']} 3D Bounding Box\n"
            f"Score={nodule['score']:.4f}"
        )
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )


