#!/usr/bin/env python3

"""
visualization.py

Operational visualization for CPMNetv2 HN25.

Input
-----
- Original CT
    NIfTI file
    or DICOM series directory

- final_detections.json
    generated by Step 22

Output
------
visualization/
├── axial/
├── coronal/
├── sagittal/
├── preview_3d/
└── viewer_annotations.json

Purpose
-------
- Doctor-facing qualitative visualization
- CT slice overlay
- Bounding box visualization
- Viewer integration metadata

IMPORTANT
---------
This is operational visualization.

No GT is used.

Coordinates used:
- original_voxel
- physical_world XYZ mm
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import matplotlib.pyplot as plt
import numpy as np
import SimpleITK as sitk
from matplotlib.patches import Rectangle
from mpl_toolkits.mplot3d.art3d import Line3DCollection


# =============================================================================
# CONFIG
# =============================================================================

WINDOW_CENTER = -600.0
WINDOW_WIDTH = 1500.0

WINDOW_MIN = (
    WINDOW_CENTER
    - WINDOW_WIDTH / 2.0
)

WINDOW_MAX = (
    WINDOW_CENTER
    + WINDOW_WIDTH / 2.0
)

MAX_VISUALIZED_NODULES = 20


# =============================================================================
# IO
# =============================================================================

def load_json(
    path: Path | str,
) -> Dict[str, Any]:

    path = Path(
        path
    )

    if not path.exists():

        raise FileNotFoundError(
            f"JSON 없음:\n{path}"
        )

    with open(
        path,
        "r",
        encoding="utf-8",
    ) as file:

        return json.load(
            file
        )


def load_nifti(
    path: Path,
) -> sitk.Image:

    return sitk.ReadImage(
        str(
            path
        ),
        sitk.sitkFloat32,
    )


def load_dicom_series(
    directory: Path,
    series_uid: Optional[str] = None,
) -> sitk.Image:

    series_ids = (
        sitk.ImageSeriesReader
        .GetGDCMSeriesIDs(
            str(
                directory
            )
        )
    )

    if not series_ids:

        raise RuntimeError(
            f"DICOM series 없음:\n{directory}"
        )

    series_ids = list(
        series_ids
    )

    if series_uid is None:

        if len(
            series_ids
        ) != 1:

            raise RuntimeError(
                "DICOM series가 여러 개 있습니다.\n"
                f"Available: {series_ids}"
            )

        selected_uid = (
            series_ids[0]
        )

    else:

        selected_uid = str(
            series_uid
        )

        if selected_uid not in series_ids:

            raise RuntimeError(
                "series_uid가 없습니다.\n"
                f"Requested: {selected_uid}\n"
                f"Available: {series_ids}"
            )

    filenames = (
        sitk.ImageSeriesReader
        .GetGDCMSeriesFileNames(
            str(
                directory
            ),
            selected_uid,
        )
    )

    reader = (
        sitk.ImageSeriesReader()
    )

    reader.SetFileNames(
        filenames
    )

    return sitk.Cast(
        reader.Execute(),
        sitk.sitkFloat32,
    )


def load_ct(
    input_path: Path | str,
    series_uid: Optional[str] = None,
) -> Tuple[
    sitk.Image,
    np.ndarray,
]:

    path = Path(
        input_path
    )

    if not path.exists():

        raise FileNotFoundError(
            f"CT 없음:\n{path}"
        )

    if path.is_dir():

        image = (
            load_dicom_series(
                directory=path,
                series_uid=series_uid,
            )
        )

    else:

        lower_name = (
            path.name.lower()
        )

        if (
            lower_name.endswith(
                ".nii"
            )
            or
            lower_name.endswith(
                ".nii.gz"
            )
        ):

            image = (
                load_nifti(
                    path
                )
            )

        else:

            raise RuntimeError(
                "지원하지 않는 CT 입력입니다."
            )

    volume = (
        sitk.GetArrayFromImage(
            image
        )
        .astype(
            np.float32
        )
    )

    return (
        image,
        volume,
    )


# =============================================================================
# DISPLAY
# =============================================================================

def window_ct(
    image: np.ndarray,
) -> np.ndarray:

    return np.clip(
        image,
        WINDOW_MIN,
        WINDOW_MAX,
    )


def clamp_index(
    value: float,
    size: int,
) -> int:

    return int(
        max(
            0,
            min(
                round(
                    value
                ),
                size - 1,
            ),
        )
    )


# =============================================================================
# BBOX HELPERS
# =============================================================================

def get_original_bbox(
    nodule: Dict[str, Any],
) -> Tuple[
    np.ndarray,
    np.ndarray,
]:

    original = (
        nodule[
            "original_voxel"
        ]
    )

    bbox_min = np.asarray(
        original[
            "bbox_min_zyx"
        ],
        dtype=np.float64,
    )

    bbox_max = np.asarray(
        original[
            "bbox_max_zyx"
        ],
        dtype=np.float64,
    )

    return (
        bbox_min,
        bbox_max,
    )


def get_original_center(
    nodule: Dict[str, Any],
) -> np.ndarray:

    return np.asarray(
        nodule[
            "original_voxel"
        ][
            "center_zyx"
        ],
        dtype=np.float64,
    )


# =============================================================================
# DRAW 2D
# =============================================================================

def draw_axial(
    volume: np.ndarray,
    nodule: Dict[str, Any],
    output_path: Path,
):

    center = (
        get_original_center(
            nodule
        )
    )

    bbox_min, bbox_max = (
        get_original_bbox(
            nodule
        )
    )

    z = clamp_index(
        center[0],
        volume.shape[0],
    )

    image = (
        volume[
            z
        ]
    )

    x_min = float(
        bbox_min[2]
    )

    y_min = float(
        bbox_min[1]
    )

    x_max = float(
        bbox_max[2]
    )

    y_max = float(
        bbox_max[1]
    )

    fig, ax = plt.subplots(
        figsize=(
            8,
            8,
        )
    )

    ax.imshow(
        window_ct(
            image
        ),
        cmap="gray",
        vmin=WINDOW_MIN,
        vmax=WINDOW_MAX,
    )

    rect = Rectangle(
        (
            x_min,
            y_min,
        ),
        x_max - x_min,
        y_max - y_min,
        fill=False,
        linewidth=2.2,
    )

    ax.add_patch(
        rect
    )

    ax.scatter(
        [
            center[2]
        ],
        [
            center[1]
        ],
        marker="x",
        s=90,
        linewidths=2,
    )

    ax.set_title(
        (
            f"{nodule['nodule_id']} | "
            f"Axial Z={z}\n"
            f"Score={nodule['score']:.4f}"
        )
    )

    ax.axis(
        "off"
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )


